CREATE TABLE IF NOT EXISTS tbl_connection (
  id           BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  name         VARCHAR(64)  NOT NULL,
  engine       VARCHAR(32)  NOT NULL,             -- mysql/postgres/clickhouse/redis/tidb
  host         VARCHAR(128) NOT NULL,
  port         INT          NOT NULL,
  env          VARCHAR(32)  NOT NULL,             -- tbl_environment.code
  policy       VARCHAR(32)  NOT NULL,             -- strict|approve-1|audit-only
  default_role VARCHAR(64),
  layer        VARCHAR(64),
  username     VARCHAR(64),                        -- real-execution credentials
  password     VARCHAR(255),
  -- TEXT,不是 VARCHAR(n)。**全库所有 db_name 列的口径都在这里**。
  --
  -- 这一列装的是「目标库」,而目标库对 sqlite 引擎就是一个**文件绝对路径**。路径长度
  -- 没有上限可言 —— 128 从来就是个错的数字,只是旧测试跑在 SQLite 上(它不检查写入
  -- 长度)所以一直没有暴露;换到 PG 上,一条 macOS 默认 TMPDIR 下的临时路径就足够
  -- 把它撑爆,报 value too long for type character varying(128)。
  --
  -- 别的表里的 db_name 是这一列的**拷贝**(审批单/审计/执行窗口/导出/异步任务/发布/
  -- 元数据…… 记的都是「这条命令打到哪个库」),所以它们必须一样宽,否则连接建得出来,
  -- 而针对它开的第一张审批单写不进去。PG 上 TEXT 与 VARCHAR(n) 存储方式完全相同,
  -- 那个上限不换来任何好处,只换来一次「路径够长才炸」的写入失败。
  db_name      TEXT,                               -- default schema / sqlite file
  tags         VARCHAR(255),                       -- comma-separated labels for group access
  status       VARCHAR(16)  NOT NULL DEFAULT 'online',  -- online|maint
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT pk_tbl_connection PRIMARY KEY (id)
);
