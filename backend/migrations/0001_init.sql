-- AegisDB — canonical schema (PostgreSQL 16+).
-- Naming: tbl_ prefix, pk_ primary keys, idx_ indexes. No physical FKs —
-- relational integrity is maintained at the application layer (backend doc §9).
-- This is the AUTHORITATIVE production schema, applied via `vela-gateway migrate`
-- and tracked in schema_migrations (see internal/bootstrap/migrate.go).
--
-- This file is a BASELINE: migrations 0001–0044 of the MySQL era collapsed into
-- the single shape they added up to. Every statement is idempotent
-- (CREATE TABLE / CREATE INDEX … IF NOT EXISTS) so applying it twice is a no-op
-- — test harnesses build the schema from this file and then let Migrate() run
-- against an empty ledger.
--
-- Types: BIGINT identity for surrogate keys, TIMESTAMPTZ for instants, TEXT for
-- unbounded blobs. Note VARCHAR(64) — not CHAR(64) — for the audit hash columns:
-- PostgreSQL's char(n) is blank-padded and would come back to Go with trailing
-- spaces, breaking the string comparison the hash chain relies on
-- (internal/service/audit_chain.go).

