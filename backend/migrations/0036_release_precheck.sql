-- 0036: 发布单上记下收单时的语法与对象检查结果。
--
-- ## 为什么存在单子上,而不是只随响应返回
--
-- 提单方(CI / 变更系统)拿到响应就走了,而后面来看这张单的是**另一个人**:审批的人、
-- 执行的人、出了事回头查的人。检查结果如果只在那一次响应里,这几个人一个都看不到。
--
-- 它也不能等到发布流程跑到某个阶段再算一遍:检查说的是"收单那一刻目标库长什么样",
-- 而发布可能几小时后才执行。晚一点算出来的是另一件事。
--
-- ## 为什么不拆成表
--
-- 这份结果是**一次检查的快照**,不查询、不统计、不关联 —— 它只被整份读出来显示。
-- 拆成行会得到一张只会被 `WHERE release_id = ?` 全取的表,外加一次联查。
--
-- 结构见 service.PrecheckResult。列可空:0036 之前的单子没有这一栏,那和"检查过、
-- 没问题"不是一回事 —— 界面必须能把这两种分开说。
ALTER TABLE tbl_release ADD COLUMN precheck MEDIUMTEXT NULL;
