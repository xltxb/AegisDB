-- 执行结果原先只存了输出和行数(result / result_rows)。失败的原因确实写在输出里 ——
-- "· 数据库执行失败: …" —— 但没有任何一列说那段文字是一次失败,于是列表上一条跑挂的
-- DROP 和一条跑成的长得一模一样,都是"已通过"。想分辨就只能去解析那段文字,而那是猜。
--
-- exec_status 和 status 是两件事,不能合并:
--
--   status      审批的结论。批了就是批了 —— 跑挂了并不会把它变回没批准,而"能不能
--               执行""按状态筛选"走的都是它。把失败写进 status,等于让一次执行事故
--               改写一次人的决定。
--   exec_status 那一次下发的结果。空 = 还没执行。
--
-- 存量数据**不回填**。这一列存在之前跑过的工单,成败无从得知 —— 把它们一律标成
-- success 是替它们编一个结果,而这一列存在的意义正是"不再靠猜"。空值的历史单在界面
-- 上照旧只说"已执行",和从前一模一样;它也不影响任何判定:能不能再执行看的是
-- executed_at(见 0028),不是这一列。
ALTER TABLE tbl_approval ADD COLUMN exec_status VARCHAR(16) NULL;
