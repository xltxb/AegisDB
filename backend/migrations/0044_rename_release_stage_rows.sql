-- 0044: `rows` → row_count。
--
-- ## 为什么换名字,而不是继续加反引号
--
-- ADR 0016 §二:列名不得是 MySQL 保留字,而补救办法是**换名字**,不是到处补反引号。
--
--   · 反引号是 MySQL 的写法。此后每一处手写 SQL 都得记得加,忘一次就是一句 1064
--     「你的语法有问题」—— 而它连是哪个词都不说,因为报错指向的是**下一个** token。
--   · 开发环境永远碰不到:那边是 SQLite,`key` / `sql` / `rows` 在它上面都是合法列名。
--     整套测试跑绿说明不了任何事,它只在第一次 migrate 的那台真机上炸。
--   · GORM 生成的语句自己会加引号,所以 ORM 那条路一直没事 —— 出事的永远是那几句
--     手写的 Where / Order。它们少得让人不会去专门检查,又多得总有一处被忘掉。
--
-- ## 为什么一个文件只有一条 ALTER
--
-- 迁移中途失败没有事务,失败之后整个文件从第一条重跑。MySQL 没有条件式 DDL
-- (CHANGE COLUMN 不支持 IF EXISTS),而 `SET @ddl := …; PREPARE …` 那套在这里也不行:
-- 迁移逐条 db.Exec,每条可能落在**不同的池连接**上,而用户变量是会话级的 —— 换个连接
-- 就是 NULL。所以走 ADR 0016 §三的另一半:一条 ALTER 独占一个文件,重跑就是从头再来
-- 一次,没有"前面几条已经生效"的中间态。同一张表的两列合并进**一条** ALTER,MySQL 8
-- 的原子 DDL 保证它整条成败。
--
-- ## 数据
--
-- CHANGE COLUMN 是重命名,不动数据,也不需要回填。旧名字在这条迁移之后不再存在 ——
-- 代码侧同一个提交里改完(model 的 column 标注 + 两处手写 SQL)。

ALTER TABLE tbl_release_stage
  CHANGE COLUMN `rows` row_count INT NOT NULL DEFAULT 0;
