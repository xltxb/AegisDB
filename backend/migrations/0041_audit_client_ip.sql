-- 0041: 审计行记下**这一下是从哪台机器发出来的** —— 客户端 IP。
--
-- 审计表此前回答得了"谁、在哪台实例上、跑了什么",唯独回答不了"他人在哪"。而事后要
-- 问的往往正是这一句:同一个账号昨夜从两个不同网段各删过一次数据,只看 actor 是一样的
-- 两行;IP 一摆出来就是两件事。账号被盗用、凭据被拿去别处跑,都只在这一列上露头。
--
-- 来源是 gin 的 ClientIP():它只在**配置过的可信代理**后面才认 X-Forwarded-For
-- (router 调过 SetTrustedProxies,默认一台都不信),所以这一列不会被客户端伪造成
-- 别的地址 —— 与 IP 白名单那道防护读的是同一个值(middleware.IPAllowlist)。
--
-- 长度 45:IPv6 完整形态(8 组 4 位十六进制 + 7 个冒号 = 39)再留出 IPv4 映射写法
-- (::ffff:255.255.255.255)的余量。
--
-- 老行留空,**不回填** —— 与 0039 / 0040 同一条:这是一张哈希链审计表,按今天能拿到
-- 的东西去补写历史行,等于在证据上动手。空 = 这一行写下时还没有这一列。
--
-- 新行起这一列进哈希载荷(service.auditHashPayload 的 "ip" 键)。理由和 0040 写过的
-- 一样:不进载荷的话,把一行的 client_ip 改掉链照样验得过 —— 行里写着什么,链就得
-- 担保什么。
--
-- 不建索引:这一列是拿来**模糊**搜的(操作人/IP 一个输入框,LIKE '%…%'),而前缀通配
-- 的 LIKE 用不上 B-Tree 索引;建一个只是让每次写入多付一份代价。按时间与实例收窄之后
-- 的结果集上再扫这一列,是这张表本来就在做的事。
ALTER TABLE tbl_audit_log ADD COLUMN client_ip VARCHAR(45) NOT NULL DEFAULT '';
