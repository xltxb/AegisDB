// gen 从源码扫描接口报错的中文,重写 apimsg 的文案表与前端 zh / en 词条里的 apiMsg 块。
//
//	cd backend && go generate ./internal/apimsg
//
// en.json5 里已有的译文按 code 保留;新句子先以中文占位,TestApiMsgEnglish 会报出来等人翻译。
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"velagateway/internal/apimsg"
	"velagateway/internal/apimsg/scan"
)

func main() {
	// go generate 在包目录(backend/internal/apimsg)下运行
	internal := filepath.Join("..")
	found, violations, err := scan.Dir(internal)
	if err != nil {
		fail(err)
	}
	for _, v := range violations {
		fmt.Fprintln(os.Stderr, "!", v)
	}
	entries := scan.Unique(found)

	var b strings.Builder
	b.WriteString("// Code generated by go generate ./internal/apimsg; DO NOT EDIT.\n\npackage apimsg\n\nvar catalog = []Entry{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t{%s, %v},\n", strconv.Quote(e.Zh), e.Fmt)
	}
	b.WriteString("}\n")
	write("catalog_gen.go", b.String())

	locales := filepath.Join("..", "..", "..", "frontend", "src", "locales")
	zh := make([]string, 0, len(entries))
	for _, e := range entries {
		ae := apimsg.Entry{Zh: e.Zh, Fmt: e.Fmt}
		zh = append(zh, fmt.Sprintf("    %s: %s,", apimsg.Code(e.Zh), quote(apimsg.Template(ae))))
	}
	replaceBlock(filepath.Join(locales, "zh.json5"), zh)

	enPath := filepath.Join(locales, "en.json5")
	old := ExistingBlock(enPath)
	en := make([]string, 0, len(entries)*2)
	missing := 0
	for _, e := range entries {
		code := apimsg.Code(e.Zh)
		v, ok := old[code]
		if !ok {
			v = quote(apimsg.Template(apimsg.Entry{Zh: e.Zh, Fmt: e.Fmt}))
			missing++
		}
		en = append(en, "    // "+strings.ReplaceAll(e.Zh, "\n", `\n`), fmt.Sprintf("    %s: %s,", code, v))
	}
	replaceBlock(enPath, en)
	fmt.Printf("apimsg: %d 条文案,en 待翻译 %d 条,违规 %d 处\n", len(entries), missing, len(violations))
}

func quote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `'`, `\'`, "\n", `\n`, "\t", `\t`)
	return "'" + r.Replace(s) + "'"
}

var entryRe = regexp.MustCompile(`^\s*(m[0-9a-f]{8}): ('(?:[^'\\]|\\.)*'),\s*$`)

// ExistingBlock 读出词条文件里 apiMsg 块现有的 code → 带引号的值。
func ExistingBlock(path string) map[string]string {
	raw, err := os.ReadFile(path)
	if err != nil {
		fail(err)
	}
	out := map[string]string{}
	in := false
	for _, line := range strings.Split(strings.ReplaceAll(string(raw), "\r\n", "\n"), "\n") {
		if strings.TrimSpace(line) == "apiMsg: {" {
			in = true
			continue
		}
		if in && strings.TrimSpace(line) == "}," {
			break
		}
		if m := entryRe.FindStringSubmatch(line); in && m != nil {
			out[m[1]] = m[2]
		}
	}
	return out
}

// replaceBlock 把文件里的 apiMsg 块换成 lines;没有就加在最外层对象的末尾。
func replaceBlock(path string, lines []string) {
	raw, err := os.ReadFile(path)
	if err != nil {
		fail(err)
	}
	src := strings.ReplaceAll(string(raw), "\r\n", "\n")
	block := "  // 接口报错文案(apiMsg.<code>),由 go generate ./internal/apimsg 生成;en 只改值,不要手改键\n  apiMsg: {\n" +
		strings.Join(lines, "\n") + "\n  },\n"
	re := regexp.MustCompile(`(?s)  // 接口报错文案\(apiMsg[^\n]*\n  apiMsg: \{\n.*?\n  \},\n`)
	if re.MatchString(src) {
		src = re.ReplaceAllLiteralString(src, block)
	} else {
		i := strings.LastIndex(src, "}")
		head := strings.TrimRight(src[:i], " \n")
		if !strings.HasSuffix(head, ",") {
			head += ","
		}
		src = head + "\n" + block + src[i:]
	}
	if strings.Contains(string(raw), "\r\n") {
		src = strings.ReplaceAll(src, "\n", "\r\n")
	}
	write(path, src)
}

func write(path, s string) {
	if err := os.WriteFile(path, []byte(s), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
