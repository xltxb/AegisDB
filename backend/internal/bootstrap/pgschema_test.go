package bootstrap

// 存储库 PG 表结构与 MySQL 的对齐。
//
// MySQL 的表结构由 migrations/*.sql 定;PG 的由 migrations/pg/*.sql 定。PG 的起点
// 0064_baseline.sql 是从"跑完 MySQL 0001-0064 的库"生成的(本文件的 TestGenPGBaseline),
// 之后两边的迁移各写一份、编号对齐。TestPGSchemaMatchesMySQL 把两边都跑一遍、逐表逐列
// 比对,任何一边漏写都会在这里红。
//
//	VELA_TEST_STORE_MYSQL=root:pw@tcp(127.0.0.1:3407)/
//	VELA_TEST_STORE_PG=host=127.0.0.1 port=5437 user=postgres password=pw sslmode=disable
//	VELA_GEN_PG_BASELINE=1   (只在要重新生成基线时设)
//
// 映射规则(决定了网关在 PG 上的行为与 MySQL 一致):
//   - 字符串一律 citext:MySQL 这边全部是 *_ci 排序规则,邮箱登录、搜索的 LIKE、唯一索引
//     都是不分大小写的;citext 保住这一点(含 LIKE)。长度上限用 CHECK 补回 —— MySQL 严格
//     模式下超长是报错,不是截断。
//   - TINYINT(1) → boolean;DATETIME(p) → timestamptz(p)(审计哈希里的时间带时区偏移,
//     不带时区的 timestamp 读回来偏移变了,审计链第一行就断 —— 见 2026-11-16 实验)。
//   - 自增 id → GENERATED BY DEFAULT AS IDENTITY(搬迁时要原样带 id 写入)。

import (
	"database/sql"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

type myCol struct {
	Name, DataType, ColumnType, Default, Extra string
	HasDefault, Nullable                       bool
	CharMax                                     int64
	DTPrec                                      int
}

type myIndex struct {
	Name    string
	Unique  bool
	Columns []string
}

type myTable struct {
	Name    string
	Cols    []myCol
	PK      []string
	Indexes []myIndex
}

// readMySQLStoreSchema 读一个已迁移好的 MySQL 存储库(当前连接的 DATABASE())的表结构。
// schema_migrations 不在内:两边的迁移账本各记各的。
func readMySQLStoreSchema(t *testing.T, db *sql.DB) []myTable {
	t.Helper()
	tables := map[string]*myTable{}
	rows, err := db.Query(`SELECT table_name, column_name, data_type, column_type, column_default, is_nullable,
			COALESCE(character_maximum_length, 0), COALESCE(datetime_precision, 0), extra
		FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name <> 'schema_migrations'
		ORDER BY table_name, ordinal_position`)
	if err != nil {
		t.Fatal(err)
	}
	var order []string
	for rows.Next() {
		var tn string
		var c myCol
		var def sql.NullString
		var nullable string
		if err := rows.Scan(&tn, &c.Name, &c.DataType, &c.ColumnType, &def, &nullable, &c.CharMax, &c.DTPrec, &c.Extra); err != nil {
			t.Fatal(err)
		}
		c.HasDefault, c.Default, c.Nullable = def.Valid, def.String, nullable == "YES"
		if tables[tn] == nil {
			tables[tn] = &myTable{Name: tn}
			order = append(order, tn)
		}
		tables[tn].Cols = append(tables[tn].Cols, c)
	}
	rows.Close()

	rows, err = db.Query(`SELECT table_name, index_name, non_unique, column_name FROM information_schema.statistics
		WHERE table_schema = DATABASE() AND table_name <> 'schema_migrations' ORDER BY table_name, index_name, seq_in_index`)
	if err != nil {
		t.Fatal(err)
	}
	idx := map[string]*myIndex{}
	var idxOrder []string
	idxTable := map[string]string{}
	for rows.Next() {
		var tn, in, cn string
		var nonUnique int
		if err := rows.Scan(&tn, &in, &nonUnique, &cn); err != nil {
			t.Fatal(err)
		}
		k := tn + "." + in
		if idx[k] == nil {
			idx[k] = &myIndex{Name: in, Unique: nonUnique == 0}
			idxOrder = append(idxOrder, k)
			idxTable[k] = tn
		}
		idx[k].Columns = append(idx[k].Columns, cn)
	}
	rows.Close()
	for _, k := range idxOrder {
		tb := tables[idxTable[k]]
		if idx[k].Name == "PRIMARY" {
			tb.PK = idx[k].Columns
			continue
		}
		tb.Indexes = append(tb.Indexes, *idx[k])
	}
	sort.Strings(order)
	out := make([]myTable, 0, len(order))
	for _, n := range order {
		out = append(out, *tables[n])
	}
	return out
}

func pqIdent(s string) string { return `"` + s + `"` }

func pgLiteral(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

// pgColumnDef 是一列在 PG 上的定义(不含列名),以及它要带的 CHECK 约束表达式(可能为空)。
func pgColumnDef(t *testing.T, tb string, c myCol) (def string, check string) {
	t.Helper()
	ty := ""
	isBool := false
	switch c.DataType {
	case "bigint":
		ty = "bigint"
	case "int":
		ty = "integer"
	case "tinyint":
		if c.ColumnType != "tinyint(1)" {
			t.Fatalf("%s.%s: 未映射的 %s", tb, c.Name, c.ColumnType)
		}
		ty, isBool = "boolean", true
	case "varchar", "char":
		ty = "citext"
		check = fmt.Sprintf("char_length(%s) <= %d", pqIdent(c.Name), c.CharMax)
	case "text":
		ty = "citext"
		check = fmt.Sprintf("octet_length(%s) <= 65535", pqIdent(c.Name))
	case "mediumtext":
		ty = "citext"
		check = fmt.Sprintf("octet_length(%s) <= 16777215", pqIdent(c.Name))
	case "datetime":
		ty = fmt.Sprintf("timestamptz(%d)", c.DTPrec)
	default:
		t.Fatalf("%s.%s: 未映射的类型 %s", tb, c.Name, c.ColumnType)
	}
	if strings.Contains(c.Extra, "auto_increment") {
		return ty + " GENERATED BY DEFAULT AS IDENTITY", ""
	}
	def = ty
	if !c.Nullable {
		def += " NOT NULL"
	}
	if c.HasDefault {
		switch {
		case strings.Contains(c.Extra, "DEFAULT_GENERATED"):
			if !strings.HasPrefix(strings.ToUpper(c.Default), "CURRENT_TIMESTAMP") {
				t.Fatalf("%s.%s: 未映射的表达式默认值 %s", tb, c.Name, c.Default)
			}
			def += " DEFAULT CURRENT_TIMESTAMP"
		case isBool:
			switch c.Default {
			case "0":
				def += " DEFAULT false"
			case "1":
				def += " DEFAULT true"
			default:
				t.Fatalf("%s.%s: 布尔默认值 %q", tb, c.Name, c.Default)
			}
		case ty == "bigint" || ty == "integer":
			def += " DEFAULT " + c.Default
		default:
			def += " DEFAULT " + pgLiteral(c.Default)
		}
	}
	return def, check
}

// pgIndexName 给索引起 PG 名字。MySQL 的索引名只在表内唯一,PG 的在整个 schema 里唯一,
// 所以统一带上表名;超过 63 字节(PG 会静默截断)就直接报错,由人来起名。
func pgIndexName(t *testing.T, tb, in string) string {
	n := tb + "__" + in
	if len(n) > 63 {
		t.Fatalf("索引名过长:%s", n)
	}
	return n
}

func pgBaselineDDL(t *testing.T, tables []myTable) string {
	t.Helper()
	var b strings.Builder
	b.WriteString(`-- 网关存储库在 PostgreSQL 上的起点,等价于 MySQL 迁移 0001-0064 跑完后的表结构。
--
-- 由 internal/bootstrap/pgschema_test.go 的 TestGenPGBaseline 从真实 MySQL 生成,**不要手改**;
-- 之后的表结构变化写成新的迁移(MySQL 的 migrations/00xx_*.sql 与这里的 pg/00xx_*.sql
-- 各一份、编号相同),TestPGSchemaMatchesMySQL 会把两边逐列比对。
--
-- 字符串列一律 citext(与 MySQL 的 *_ci 一致:不分大小写的比较、LIKE、唯一索引),
-- 长度上限由 CHECK 约束补回。需要 PostgreSQL 13+(citext 为受信扩展,库属主即可创建)。

CREATE EXTENSION IF NOT EXISTS citext;
`)
	for _, tb := range tables {
		var parts []string
		for _, c := range tb.Cols {
			def, check := pgColumnDef(t, tb.Name, c)
			col := "  " + pqIdent(c.Name) + " " + def
			if check != "" {
				col += " CHECK (" + check + ")"
			}
			parts = append(parts, col)
		}
		if len(tb.PK) == 0 {
			t.Fatalf("%s 没有主键", tb.Name)
		}
		pk := make([]string, len(tb.PK))
		for i, c := range tb.PK {
			pk[i] = pqIdent(c)
		}
		parts = append(parts, "  PRIMARY KEY ("+strings.Join(pk, ", ")+")")
		fmt.Fprintf(&b, "\nCREATE TABLE %s (\n%s\n);\n", pqIdent(tb.Name), strings.Join(parts, ",\n"))
		for _, ix := range tb.Indexes {
			cols := make([]string, len(ix.Columns))
			for i, c := range ix.Columns {
				cols[i] = pqIdent(c)
			}
			u := ""
			if ix.Unique {
				u = "UNIQUE "
			}
			fmt.Fprintf(&b, "CREATE %sINDEX %s ON %s (%s);\n", u, pqIdent(pgIndexName(t, tb.Name, ix.Name)), pqIdent(tb.Name), strings.Join(cols, ", "))
		}
	}
	return b.String()
}

// migratedMySQLStore 建一个空库、跑完全部 MySQL 迁移,返回它的 *sql.DB。
func migratedMySQLStore(t *testing.T, base, name string) *sql.DB {
	t.Helper()
	admin, err := sql.Open("mysql", base)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { admin.Exec("DROP DATABASE IF EXISTS " + name); admin.Close() })
	_, _ = admin.Exec("DROP DATABASE IF EXISTS " + name)
	if _, err := admin.Exec("CREATE DATABASE " + name + " CHARACTER SET utf8mb4"); err != nil {
		t.Fatal(err)
	}
	cfg := &Config{}
	cfg.Database.Driver = "mysql"
	cfg.Database.MySQLDSN = base + name + "?charset=utf8mb4&parseTime=true&loc=Local"
	cfg.Gateway.StrictMode = true
	g, err := OpenDB(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if err := Migrate(cfg, g); err != nil {
		t.Fatalf("mysql migrate: %v", err)
	}
	s, _ := g.DB()
	t.Cleanup(func() { s.Close() })
	return s
}

func TestGenPGBaseline(t *testing.T) {
	base := os.Getenv("VELA_TEST_STORE_MYSQL")
	if base == "" || os.Getenv("VELA_GEN_PG_BASELINE") == "" {
		t.Skip("重新生成 PG 基线:设 VELA_TEST_STORE_MYSQL 与 VELA_GEN_PG_BASELINE=1")
	}
	db := migratedMySQLStore(t, base, fmt.Sprintf("vt_pggen_%d", os.Getpid()))
	ddl := pgBaselineDDL(t, readMySQLStoreSchema(t, db))
	path := filepath.Join("..", "..", "migrations", "pg", "0064_baseline.sql")
	if err := os.WriteFile(path, []byte(ddl), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("已写 %s(%d 字节)", path, len(ddl))
}

// colShape 是一列可比较的"形状":两边各自换算成它再比。
type colShape struct {
	Type     string // bigint | integer | boolean | citext | timestamptz(p)
	NotNull  bool
	Default  string // 归一化后的默认值;无默认为空
	Identity bool
	Limit    string // char_length<=n | octet_length<=n | 空
}

func expectedShape(t *testing.T, tb string, c myCol) colShape {
	def, check := pgColumnDef(t, tb, c)
	s := colShape{Identity: strings.Contains(def, "IDENTITY"), NotNull: strings.Contains(def, "NOT NULL") || strings.Contains(def, "IDENTITY")}
	s.Type = strings.Fields(def)[0]
	if i := strings.Index(def, " DEFAULT "); i >= 0 && !s.Identity {
		s.Default = normDefault(def[i+len(" DEFAULT "):])
	}
	if check != "" {
		s.Limit = normLimit(check)
	}
	return s
}

var limitRe = regexp.MustCompile(`(char_length|octet_length)\(.*?<=\s*(\d+)`)

func normLimit(expr string) string {
	m := limitRe.FindStringSubmatch(expr)
	if m == nil {
		return "?" + expr
	}
	return m[1] + "<=" + m[2]
}

func normDefault(d string) string {
	d = strings.TrimSpace(d)
	d = strings.TrimSuffix(d, "::citext")
	return d
}

func TestPGSchemaMatchesMySQL(t *testing.T) {
	my := os.Getenv("VELA_TEST_STORE_MYSQL")
	pg := os.Getenv("VELA_TEST_STORE_PG")
	if my == "" || pg == "" {
		t.Skip("需要 VELA_TEST_STORE_MYSQL 与 VELA_TEST_STORE_PG")
	}
	want := readMySQLStoreSchema(t, migratedMySQLStore(t, my, fmt.Sprintf("vt_pgcmp_%d", os.Getpid())))

	name := fmt.Sprintf("vt_pgcmp_%d", os.Getpid())
	admin, err := pgAdmin(pg)
	if err != nil {
		t.Fatal(err)
	}
	_, _ = admin.Exec("DROP DATABASE IF EXISTS " + name + " WITH (FORCE)")
	if _, err := admin.Exec("CREATE DATABASE " + name); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { admin.Exec("DROP DATABASE IF EXISTS " + name + " WITH (FORCE)"); admin.Close() })
	cfg := &Config{}
	cfg.Database.Driver = "postgres"
	cfg.Database.PostgresDSN = pg + " dbname=" + name
	cfg.Gateway.StrictMode = true
	g, err := OpenDB(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if err := Migrate(cfg, g); err != nil {
		t.Fatalf("pg migrate: %v", err)
	}
	db, _ := g.DB()
	defer db.Close()

	// 实际的列
	got := map[string]map[string]colShape{}
	rows, err := db.Query(`SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
			COALESCE(pg_get_expr(d.adbin, d.adrelid), ''), a.attidentity <> ''
		FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
		LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
		WHERE n.nspname = current_schema() AND c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped
			AND c.relname <> 'schema_migrations'`)
	if err != nil {
		t.Fatal(err)
	}
	for rows.Next() {
		var tb, col, ty, def string
		var s colShape
		if err := rows.Scan(&tb, &col, &ty, &s.NotNull, &def, &s.Identity); err != nil {
			t.Fatal(err)
		}
		ty = strings.Replace(ty, "timestamp(", "timestamptz(", 1)
		ty = strings.Replace(ty, ") with time zone", ")", 1)
		s.Type, s.Default = ty, normDefault(def)
		if got[tb] == nil {
			got[tb] = map[string]colShape{}
		}
		got[tb][col] = s
	}
	rows.Close()
	// 长度约束(列级 CHECK)
	rows, err = db.Query(`SELECT c.relname, a.attname, pg_get_constraintdef(k.oid)
		FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
		JOIN pg_attribute a ON a.attrelid = k.conrelid AND a.attnum = k.conkey[1]
		WHERE n.nspname = current_schema() AND k.contype = 'c'`)
	if err != nil {
		t.Fatal(err)
	}
	for rows.Next() {
		var tb, col, def string
		if err := rows.Scan(&tb, &col, &def); err != nil {
			t.Fatal(err)
		}
		s := got[tb][col]
		s.Limit = normLimit(def)
		got[tb][col] = s
	}
	rows.Close()
	// 索引(含主键):表 → "u:a,b" / "i:a" / "pk:a"
	gotIdx := map[string][]string{}
	rows, err = db.Query(`SELECT t.relname, ix.indisprimary, ix.indisunique,
			(SELECT string_agg(a.attname, ',' ORDER BY k.ord) FROM unnest(ix.indkey) WITH ORDINALITY k(attnum, ord)
			 JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = k.attnum)
		FROM pg_index ix JOIN pg_class t ON t.oid = ix.indrelid JOIN pg_namespace n ON n.oid = t.relnamespace
		WHERE n.nspname = current_schema() AND t.relname <> 'schema_migrations'`)
	if err != nil {
		t.Fatal(err)
	}
	for rows.Next() {
		var tb, cols string
		var pk, uq bool
		if err := rows.Scan(&tb, &pk, &uq, &cols); err != nil {
			t.Fatal(err)
		}
		gotIdx[tb] = append(gotIdx[tb], idxKey(pk, uq, cols))
	}
	rows.Close()

	if len(got) != len(want) {
		t.Errorf("表数:PG %d,MySQL %d", len(got), len(want))
	}
	checked := 0
	for _, tb := range want {
		if got[tb.Name] == nil {
			t.Errorf("PG 缺表 %s", tb.Name)
			continue
		}
		if len(got[tb.Name]) != len(tb.Cols) {
			t.Errorf("%s 列数:PG %d,MySQL %d", tb.Name, len(got[tb.Name]), len(tb.Cols))
		}
		for _, c := range tb.Cols {
			g, ok := got[tb.Name][c.Name]
			if !ok {
				t.Errorf("PG 缺列 %s.%s", tb.Name, c.Name)
				continue
			}
			if w := expectedShape(t, tb.Name, c); g != w {
				t.Errorf("%s.%s:PG %+v,按 MySQL 应为 %+v", tb.Name, c.Name, g, w)
			}
			checked++
		}
		wantIdx := []string{idxKey(true, true, strings.Join(tb.PK, ","))}
		for _, ix := range tb.Indexes {
			wantIdx = append(wantIdx, idxKey(false, ix.Unique, strings.Join(ix.Columns, ",")))
		}
		sort.Strings(wantIdx)
		gi := append([]string(nil), gotIdx[tb.Name]...)
		sort.Strings(gi)
		if strings.Join(gi, " ") != strings.Join(wantIdx, " ") {
			t.Errorf("%s 索引:PG %v,MySQL %v", tb.Name, gi, wantIdx)
		}
	}
	t.Logf("比对了 %d 张表、%d 列", len(want), checked)
}

func idxKey(pk, unique bool, cols string) string {
	switch {
	case pk:
		return "pk:" + cols
	case unique:
		return "u:" + cols
	}
	return "i:" + cols
}
